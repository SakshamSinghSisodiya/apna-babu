export const t = (lang: LangId, key: string, vars?: Record<string, string>): string => {
  let s = UI[lang][key] ?? UI.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
};

